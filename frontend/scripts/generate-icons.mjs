const source = readFileSync(CONTENT, 'utf8');
const slugs = [...new Set([...source.matchAll(/icon: '([^']+)'/g)].map((m) => m[1]))].sort();

const entries = [];
const missing = [];

for (const slug of slugs) {
  const key = `si${slug.charAt(0).toUpperCase()}${slug.slice(1)}`;
  const icon = simpleIcons[key];
  if (icon?.path) {
    entries.push([slug, icon.path, icon.title]);
  } else if (FALLBACKS[slug]) {
    entries.push([slug, FALLBACKS[slug], 'hand-drawn fallback']);
    missing.push(slug);
  } else {
    throw new Error(`No icon for "${slug}" — add a path to FALLBACKS in this script.`);
  }
}

const body = entries
  .map(([slug, path, title]) => `  // ${title}\n  ${slug}: '${path.replace(/'/g, "\\'")}',`)
  .join('\n');

writeFileSync(
  OUT,
  `// GENERATED by scripts/generate-icons.mjs — do not edit by hand.
// Source: simple-icons, plus hand-drawn marks for slugs it does not carry.

export const ICON_PATHS: Record<string, string> = {
${body}
};
`,
  'utf8',
);

console.log(`Wrote ${entries.length} icons to src/content/icons.ts`);
if (missing.length) console.log(`Fallback marks used for: ${missing.join(', ')}`);
